/** Цвет срока: красный у просрочки, оранжевый у «сегодня», обычный у остальных. */
export function dueTone(status: ControlOrder['status']): string {
  if (status === 'overdue') return 'armr-d r';
  if (status === 'dueToday') return 'armr-d a';
  return 'armr-d';
}
