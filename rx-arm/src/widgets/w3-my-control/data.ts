export function byTab(orders: ControlOrder[], tab: ControlTab): ControlOrder[] {
  if (tab === 'overdue') return orders.filter((o) => o.status === 'overdue');
  if (tab === 'dueToday') return orders.filter((o) => o.status === 'dueToday');
  return orders;
}

