// ============================================================
// types.ts — контракт блока «Здоровье процесса „Поручения“»: сводка по видам поручений.
// Здоровье — доля поручений, закрытых в срок; окрашивается по порогу.
// ============================================================

export interface ProcessRow {
  /** Вид поручений: «На контроле», «Без контроля». */
  kind: string;
  total: number;
  overdue: number;
  /** Здоровье, 0..100. */
  health: number;
}

export interface ProcessHealthData {
  rows: ProcessRow[];
  /** Ниже порога полоса здоровья красная, на пороге и выше — зелёная. */
  healthThreshold: number;
}
