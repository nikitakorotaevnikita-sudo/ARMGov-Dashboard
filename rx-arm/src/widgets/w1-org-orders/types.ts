/** Тон плитки: обычная (синяя), внимание (оранжевая), риск (красная). */
export type TileTone = 'normal' | 'orange' | 'red';

export interface OrgTile {
  value: number;
  label: string;
  tone: TileTone;
}

export interface OrgOrdersData {
  /** В работе — активные поручения без признака просрочки. */
  inWork: number;
  /** Срок наступает сегодня. */
  dueToday: number;
  /** Срок нарушен. */
  overdue: number;
  /** Срок истекает в ближайшие 7 дней. */
  dueIn7: number;
}
