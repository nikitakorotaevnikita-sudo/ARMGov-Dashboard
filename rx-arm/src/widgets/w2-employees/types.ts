// ============================================================
// types.ts — контракт блока «Статус исполнения поручений по сотрудникам».
// Состав блока задаёт сам руководитель через «Параметры виджета» (диалог .dcp):
// показываются только выбранные сотрудники, лимита по количеству нет.
// ============================================================

export interface Employee {
  /** Идентификатор сотрудника; в демо — транслит ФИО, на стенде — ид сотрудника RX. */
  id: string;
  name: string;
  position: string;
  /** Фото сотрудника: data-URI в демо, ссылка на карточку RX — на стенде. */
  photo: string;
  /** Активные поручения. */
  inWork: number;
  /** Срок наступает сегодня. */
  dueToday: number;
  /** Срок нарушен — карточка получает красную верхнюю грань и метку «Просрочки». */
  overdue: number;
}

export interface EmployeesData {
  employees: Employee[];
  /** Кого показывать в блоке. Пустой список = блок показывает «Сотрудники не выбраны». */
  selected: string[];
}
